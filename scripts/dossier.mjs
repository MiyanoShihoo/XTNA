#!/usr/bin/env node
/**
 * XTNA dossier exporter: turn an Evidence bundle into a reviewable Markdown document.
 *
 * It reports only what the bundle states. Missing sections stay missing; nothing is
 * reconstructed from guesswork.
 */
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const args = process.argv.slice(2);
const flag = (name) => {
  const index = args.indexOf(`--${name}`);
  return index >= 0 ? args[index + 1] : undefined;
};

const evidencePath = flag("evidence");
const format = flag("format") ?? "markdown";
if (evidencePath === undefined) {
  process.stderr.write(
    "usage: node scripts/dossier.mjs --evidence <bundle.json> [--overlay <binary>] [--api-spec <openapi.json>] [--out report.md|report.html|report.pdf] [--format markdown|html|pdf] [--title text]\n",
  );
  process.exit(2);
}
if (!["markdown", "html", "pdf"].includes(format)) {
  process.stderr.write("--format must be markdown, html or pdf\n");
  process.exit(2);
}

const bundle = JSON.parse(await readFile(resolve(evidencePath), "utf8"));
const title = flag("title") ?? "XTNA technical dossier";
const overlayBinary = flag("overlay");
const outPath = flag("out");

const artifacts = Array.isArray(bundle.artifacts) ? bundle.artifacts : [];
const records = Array.isArray(bundle.records) ? bundle.records : [];
const providers = Array.isArray(bundle.providers) ? bundle.providers : [];
const unknowns = Array.isArray(bundle.unknowns) ? bundle.unknowns : [];
const environments = Array.isArray(bundle.environments)
  ? bundle.environments
  : [];

const lines = [];
lines.push(`# ${title}`, "");
lines.push(
  `Generated by XTNA on ${new Date().toISOString()} from \`${evidencePath}\`.`,
  "",
);
lines.push(
  "> This document projects a stored Evidence bundle. It does not add observations;",
);
lines.push(
  "> every claim below is traceable to an evidence record in that bundle.",
  "",
);

lines.push("## Targets", "");
if (artifacts.length === 0)
  lines.push("No artifacts are recorded in this bundle.", "");
else {
  lines.push("| Format | Architecture | SHA-256 |", "| --- | --- | --- |");
  for (const artifact of artifacts)
    lines.push(
      `| ${artifact.format ?? "unknown"} | ${artifact.architecture ?? "—"} | \`${artifact.digest?.sha256 ?? "—"}\` |`,
    );
  lines.push("");
}

const diagramLabel = (value) =>
  String(value ?? "unknown")
    .replaceAll('"', "'")
    .replaceAll("`", "'")
    .replace(/\s+/gu, " ")
    .slice(0, 120);
lines.push("## Architecture", "");
lines.push("```mermaid", "flowchart LR");
const graphArtifacts = artifacts.slice(0, 8);
const graphProviders = providers.slice(0, 8);
const graphRecords = records.slice(0, 16);
if (graphArtifacts.length === 0) lines.push(`  B["Evidence bundle"]`);
else
  for (const [index, artifact] of graphArtifacts.entries())
    lines.push(
      `  A${String(index)}["${diagramLabel(`${artifact.format ?? "unknown"} ${artifact.architecture ?? ""}`.trim())}"]`,
    );
if (graphProviders.length === 0) lines.push(`  P0["provider unknown"]`);
else
  for (const [index, provider] of graphProviders.entries())
    lines.push(
      `  P${String(index)}["${diagramLabel(`${provider.id ?? "unknown"}${provider.version ? ` v${provider.version}` : ""}`)}"]`,
    );
for (const [index, record] of graphRecords.entries())
  lines.push(
    `  R${String(index)}["${diagramLabel(record.operation ?? "record")}"]`,
  );
const providerIndex = new Map(
  graphProviders.map((provider, index) => [provider.id ?? "unknown", index]),
);
for (let index = 0; index < Math.max(graphArtifacts.length, 1); index += 1)
  lines.push(
    `  ${graphArtifacts.length === 0 ? "B" : `A${String(index)}`} --> P0`,
  );
for (const [index, record] of graphRecords.entries()) {
  const target = providerIndex.get(record.provider?.id ?? "unknown") ?? 0;
  lines.push(`  P${String(target)} --> R${String(index)}`);
}
lines.push("```", "");

const mermaidText = (value) =>
  String(value ?? "")
    .replace(/[\r\n]+/gu, " ")
    .replace(/;/gu, ",")
    .replace(/\s+/gu, " ")
    .trim()
    .slice(0, 120);

const scenarioTransactions = () => {
  const transactions = new Map();
  for (const record of records) {
    const payload =
      record !== null && typeof record === "object"
        ? (record.normalized_result ?? record.result ?? record)
        : undefined;
    const items = payload?.events?.items;
    if (!Array.isArray(items)) continue;
    for (const item of items) {
      if (item === null || typeof item !== "object") continue;
      if (typeof item.transaction_id !== "string") continue;
      const entry = transactions.get(item.transaction_id) ?? {};
      if (item.kind === "request") entry.request = item;
      else if (item.kind === "response") entry.response = item;
      transactions.set(item.transaction_id, entry);
    }
  }
  return [...transactions.entries()]
    .filter(([, entry]) => entry.request !== undefined)
    .sort(
      (left, right) =>
        Number(left[1].request.sequence ?? 0) -
        Number(right[1].request.sequence ?? 0),
    );
};

const sequence = scenarioTransactions();
lines.push("## Interaction sequence", "");
lines.push("```mermaid", "sequenceDiagram");
if (sequence.length > 0) {
  lines.push("  participant B as Browser", "  participant S as Server");
  for (const [, entry] of sequence.slice(0, 20)) {
    const request = entry.request;
    const method = mermaidText(request.method ?? "GET").toUpperCase();
    let path = "/";
    try {
      path = new URL(String(request.url ?? "")).pathname;
    } catch {
      path = String(request.url ?? "/").split("?")[0] || "/";
    }
    lines.push(`  B->>S: ${method} ${mermaidText(path)}`);
    const response = entry.response;
    lines.push(
      `  S-->>B: ${response === undefined ? "unobserved" : String(response.status ?? "?")}`,
    );
  }
  if (sequence.length > 20)
    lines.push("  Note over B,S: truncated at 20 transactions");
} else if (records.length > 0) {
  const provider = String(records[0]?.provider?.id ?? "provider");
  lines.push(
    "  participant A as Agent",
    `  participant P as ${mermaidText(provider)}`,
  );
  for (const record of records.slice(0, 20))
    lines.push(`  A->>P: ${mermaidText(record.operation ?? "operation")}`);
  if (records.length > 20)
    lines.push("  Note over A,P: truncated at 20 records");
} else {
  lines.push("  Note over B: no recorded interactions");
}
lines.push("```", "");
lines.push(
  "> Projection of recorded request/response order. It is not a runtime trace and implies no",
);
lines.push(
  "> timing, concurrency or causation beyond the recorded sequence.",
  "",
);
lines.push("## Module responsibility matrix", "");
if (records.length === 0)
  lines.push("No provider operations are recorded.", "");
else {
  const modules = new Map();
  for (const record of records) {
    const operation = String(record.operation ?? "unknown");
    const provider = String(record.provider?.id ?? "unknown");
    const key = `${provider}\0${operation}`;
    modules.set(key, (modules.get(key) ?? 0) + 1);
  }
  lines.push("| Provider | Operation | Records |", "| --- | --- | ---: |");
  for (const [key, count] of [...modules].sort(([left], [right]) =>
    left.localeCompare(right),
  )) {
    const [provider, operation] = key.split("\0");
    lines.push(`| ${provider} | ${operation} | ${String(count)} |`);
  }
  lines.push("");
}

lines.push("## Records", "");
if (records.length === 0)
  lines.push("No evidence records are stored in this bundle.", "");
else {
  lines.push(
    "| Operation | Provider | Authority | Confidence | Limitations | Evidence |",
    "| --- | --- | --- | --- | ---: | --- |",
  );
  for (const record of records) {
    const limitations = Array.isArray(record.limitations)
      ? record.limitations.length
      : 0;
    const id = String(record.evidence_id ?? "");
    lines.push(
      `| ${record.operation ?? "—"} | ${record.provider?.id ?? "—"} | ${record.authority ?? "—"} | ${record.confidence ?? "—"} | ${String(limitations)} | \`${id.slice(0, 19)}…\` |`,
    );
  }
  lines.push("");
}

const limitations = [];
for (const record of records)
  for (const limitation of record.limitations ?? [])
    limitations.push(`${record.operation ?? "record"}: ${limitation}`);
const uniqueLimitations = [...new Set(limitations)];
lines.push("## Limitations", "");
if (uniqueLimitations.length === 0)
  lines.push("The bundle records no limitations.", "");
else
  for (const limitation of uniqueLimitations.slice(0, 200))
    lines.push(`- ${limitation}`);
lines.push("");

lines.push("## Unknowns", "");
if (unknowns.length === 0)
  lines.push("The bundle records no explicit unknowns.", "");
else {
  lines.push(
    "| Domain | Severity | Status | Question |",
    "| --- | --- | --- | --- |",
  );
  for (const unknown of unknowns.slice(0, 100))
    lines.push(
      `| ${unknown.domain ?? "—"} | ${unknown.severity ?? "—"} | ${unknown.status ?? "—"} | ${String(unknown.question ?? "").replaceAll("|", "\\|")} |`,
    );
  lines.push("");
}

lines.push("## Providers", "");
if (providers.length === 0) lines.push("No provider identity is recorded.", "");
else
  for (const provider of providers)
    lines.push(
      `- ${provider.id ?? "unknown"} ${provider.version ? `v${provider.version}` : ""}`,
    );
lines.push("");

if (environments.length > 0) {
  lines.push("## Environments", "");
  for (const environment of environments)
    lines.push(`- ${JSON.stringify(environment)}`);
  lines.push("");
}

if (overlayBinary !== undefined) {
  const overlay = JSON.parse(
    await readFile(resolve(overlayBinary), "utf8").catch(
      () => '{"entries":[]}',
    ),
  );
  lines.push("## Symbol overlay", "");
  if (!Array.isArray(overlay.entries) || overlay.entries.length === 0)
    lines.push("No overlay entries for this binary.", "");
  else {
    lines.push(
      "| Address | Kind | Confidence | Name | Type |",
      "| --- | --- | --- | --- | --- |",
    );
    for (const entry of overlay.entries)
      lines.push(
        `| \`${entry.address_hex}\` | ${entry.kind} | ${entry.confidence} | \`${entry.name}\` | ${entry.type ?? "—"} |`,
      );
    lines.push("");
  }
}

const apiSpecPath = flag("api-spec");
if (apiSpecPath !== undefined) {
  const spec = JSON.parse(await readFile(resolve(apiSpecPath), "utf8"));
  const operations = [];
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    if (item === null || typeof item !== "object") continue;
    for (const [method, operation] of Object.entries(item)) {
      if (operation === null || typeof operation !== "object") continue;
      if (
        !["get", "put", "post", "delete", "patch", "head", "options"].includes(
          method,
        )
      )
        continue;
      const parameters = [
        ...(item.parameters ?? []),
        ...(operation.parameters ?? []),
      ]
        .map((parameter) => parameter?.name ?? parameter?.$ref ?? "?")
        .join(", ");
      operations.push({
        method: method.toUpperCase(),
        path,
        operationId: operation.operationId ?? "—",
        parameters: parameters.length === 0 ? "—" : parameters,
        responses: Object.keys(operation.responses ?? {}).join(", ") || "—",
      });
    }
  }
  operations.sort(
    (left, right) =>
      left.path.localeCompare(right.path) ||
      left.method.localeCompare(right.method),
  );
  lines.push("## Interface dictionary", "");
  if (operations.length === 0)
    lines.push("The supplied OpenAPI document declares no operations.", "");
  else {
    lines.push(
      "| Method | Path | Operation | Parameters | Responses |",
      "| --- | --- | --- | --- | --- |",
    );
    for (const operation of operations.slice(0, 200))
      lines.push(
        `| ${operation.method} | \`${operation.path}\` | ${operation.operationId} | ${operation.parameters} | ${operation.responses} |`,
      );
    lines.push("");
  }
}

lines.push("## Remediation suggestions", "");
const remediation = [];
for (const unknown of unknowns)
  for (const probe of unknown.recommended_probes ?? [])
    if (probe !== null && typeof probe === "object")
      remediation.push({
        question: String(unknown.question ?? "—"),
        probe: String(probe.operation ?? "—"),
        rationale: String(probe.rationale ?? "—"),
      });
if (remediation.length === 0)
  lines.push(
    "The bundle records no suggested probes. Limitations above state what is unverified; add probes to the unknown records to populate this section.",
    "",
  );
else {
  lines.push("| Unknown | Suggested probe | Why |", "| --- | --- | --- |");
  for (const item of remediation.slice(0, 100))
    lines.push(
      `| ${item.question.replaceAll("|", "\\|")} | \`${item.probe}\` | ${item.rationale.replaceAll("|", "\\|")} |`,
    );
  lines.push("");
}

lines.push("## Reproduction", "");
lines.push("```bash");
lines.push(`git clone https://github.com/MiyanoShihoo/XTNA.git`);
lines.push(`cd XTNA && npm ci --ignore-scripts && npm run compile`);
lines.push(
  `node scripts/rea.mjs inspect-artifact <target> --format json --detail summary --evidence_output evidence.json`,
);
lines.push("```", "");

const escapeHtml = (value) =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
const inlineHtml = (value) =>
  escapeHtml(value).replaceAll(
    /`([^`]+)`/gu,
    (_match, code) => `<code>${code}</code>`,
  );
const tableCells = (line) =>
  line
    .trim()
    .replace(/^\|/u, "")
    .replace(/\|$/u, "")
    .split("|")
    .map((cell) => cell.trim());
const isTable = (lines, index) =>
  lines[index]?.startsWith("|") === true &&
  /^\|[\s:|-]+\|$/u.test(lines[index + 1] ?? "");
const markdownToHtml = (markdown) => {
  const lines = markdown.split("\n");
  const output = [];
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index] ?? "";
    if (line.startsWith("```")) {
      const language = line.slice(3).trim();
      const body = [];
      for (index += 1; index < lines.length; index += 1) {
        if (lines[index] === "```") break;
        body.push(lines[index] ?? "");
      }
      output.push(
        language === "mermaid"
          ? `<pre class="mermaid">${escapeHtml(body.join("\n"))}</pre>`
          : `<pre><code class="language-${escapeHtml(language)}">${escapeHtml(body.join("\n"))}</code></pre>`,
      );
      continue;
    }
    if (line.startsWith("## ")) {
      output.push(`<h2>${inlineHtml(line.slice(3))}</h2>`);
      continue;
    }
    if (line.startsWith("# ")) {
      output.push(`<h1>${inlineHtml(line.slice(2))}</h1>`);
      continue;
    }
    if (isTable(lines, index)) {
      const headers = tableCells(line);
      index += 2;
      const rows = [];
      for (; index < lines.length && lines[index]?.startsWith("|"); index += 1)
        rows.push(tableCells(lines[index]));
      output.push(
        `<table><thead><tr>${headers.map((cell) => `<th>${inlineHtml(cell)}</th>`).join("")}</tr></thead><tbody>${rows.map((row) => `<tr>${row.map((cell) => `<td>${inlineHtml(cell)}</td>`).join("")}</tr>`).join("")}</tbody></table>`,
      );
      index -= 1;
      continue;
    }
    if (line.startsWith("- ")) {
      const items = [];
      for (; index < lines.length && lines[index]?.startsWith("- "); index += 1)
        items.push(lines[index].slice(2));
      output.push(
        `<ul>${items.map((item) => `<li>${inlineHtml(item)}</li>`).join("")}</ul>`,
      );
      index -= 1;
      continue;
    }
    if (line.trim().length === 0) continue;
    const paragraph = [line];
    for (
      index += 1;
      index < lines.length &&
      lines[index]?.trim().length > 0 &&
      !lines[index]?.startsWith("#") &&
      !lines[index]?.startsWith("|") &&
      !lines[index]?.startsWith("- ") &&
      !lines[index]?.startsWith("```");
      index += 1
    )
      paragraph.push(lines[index] ?? "");
    output.push(`<p>${inlineHtml(paragraph.join(" "))}</p>`);
    index -= 1;
  }
  return output.join("\n");
};
const renderHtml = (markdown) => `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escapeHtml(title)}</title>
  <style>
    body { font: 15px/1.55 system-ui, sans-serif; margin: 2rem auto; max-width: 72rem; padding: 0 1.25rem; color: #1f2328; }
    h1, h2 { line-height: 1.25; }
    table { border-collapse: collapse; width: 100%; margin: 1rem 0; }
    th, td { border: 1px solid #d0d7de; padding: .45rem .6rem; text-align: left; vertical-align: top; }
    th { background: #f6f8fa; }
    code, pre { background: #f6f8fa; border-radius: 6px; }
    code { padding: .1rem .3rem; }
    pre { padding: .8rem; overflow: auto; }
    .mermaid { background: transparent; }
  </style>
</head>
<body>
${markdownToHtml(markdown)}
  <script type="module">
    import mermaid from "https://cdn.jsdelivr.net/npm/mermaid@11/dist/mermaid.esm.min.mjs";
    mermaid.initialize({ startOnLoad: true });
  </script>
</body>
</html>
`;

const pdfEscape = (value) =>
  value
    .replace(/\\/gu, "\\\\")
    .replace(/\(/gu, "\\(")
    .replace(/\)/gu, "\\)")
    .replace(/[^\x20-\x7e]/gu, "?");

const wrapPdfLine = (line, width = 95) => {
  if (line.length === 0) return [""];
  const rows = [];
  let current = "";
  for (const word of line.split(" ")) {
    const candidate = current.length === 0 ? word : current + " " + word;
    if (candidate.length > width && current.length > 0) {
      rows.push(current);
      current = word;
    } else current = candidate;
  }
  rows.push(current);
  return rows;
};

const plainDossierLines = (markdown) => {
  const out = [];
  const source = markdown.split("\n");
  for (let index = 0; index < source.length; index += 1) {
    const line = source[index] ?? "";
    if (line.startsWith("```")) {
      for (
        index += 1;
        index < source.length && source[index] !== "```";
        index += 1
      );
      continue;
    }
    if (line.trim().length === 0) {
      out.push("");
      continue;
    }
    let text = line
      .replace(/^#+\s*/u, "")
      .replace(/`/gu, "")
      .replace(/^\|\s*/u, "")
      .replace(/\s*\|$/u, "")
      .replace(/\s*\|\s*/gu, " | ");
    if (text.startsWith("- ")) text = "- " + text.slice(2);
    out.push(text);
  }
  return out;
};

/** Minimal text-only PDF 1.4 writer: Helvetica, A4, 52 lines per page. */
const buildPdf = (documentTitle, bodyLines) => {
  const wrapped = [documentTitle, "", ...bodyLines].flatMap((line) =>
    wrapPdfLine(line),
  );
  const perPage = 52;
  const pages = [];
  for (let index = 0; index < wrapped.length; index += perPage)
    pages.push(wrapped.slice(index, index + perPage));
  if (pages.length === 0) pages.push([""]);
  const firstPageId = 4;
  const objects = [];
  objects[1] = "<< /Type /Catalog /Pages 2 0 R >>";
  objects[2] = `<< /Type /Pages /Kids [${pages
    .map((_page, index) => `${String(firstPageId + index * 2)} 0 R`)
    .join(" ")}] /Count ${String(pages.length)} >>`;
  objects[3] =
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>";
  pages.forEach((pageLines, index) => {
    const pageId = firstPageId + index * 2;
    const contentId = pageId + 1;
    objects[pageId] =
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 3 0 R >> >> /Contents ${String(contentId)} 0 R >>`;
    const content = [
      "BT",
      "/F1 10 Tf",
      "14 TL",
      "50 800 Td",
      ...pageLines.flatMap((line) => [`(${pdfEscape(line)}) Tj`, "T*"]),
      "ET",
    ].join("\n");
    objects[contentId] =
      `<< /Length ${String(Buffer.byteLength(content, "latin1"))} >>\nstream\n${content}\nendstream`;
  });
  let pdf = "%PDF-1.4\n";
  const offsets = [];
  for (let id = 1; id < objects.length; id += 1) {
    offsets[id] = Buffer.byteLength(pdf, "latin1");
    pdf += `${String(id)} 0 obj\n${objects[id]}\nendobj\n`;
  }
  const xrefOffset = Buffer.byteLength(pdf, "latin1");
  let xref = `xref\n0 ${String(objects.length)}\n0000000000 65535 f \n`;
  for (let id = 1; id < objects.length; id += 1)
    xref += `${String(offsets[id]).padStart(10, "0")} 00000 n \n`;
  pdf +=
    xref +
    `trailer\n<< /Size ${String(objects.length)} /Root 1 0 R >>\nstartxref\n${String(xrefOffset)}\n%%EOF\n`;
  return Buffer.from(pdf, "latin1");
};

const markdown = `${lines.join("\n")}\n`;
if (format === "pdf" && outPath === undefined) {
  process.stderr.write("--format pdf requires --out <report.pdf>\n");
  process.exit(2);
}
const rendered =
  format === "html"
    ? renderHtml(markdown)
    : format === "pdf"
      ? buildPdf(title, plainDossierLines(markdown))
      : markdown;
if (outPath === undefined) process.stdout.write(rendered);
else {
  await writeFile(resolve(outPath), rendered);
  process.stderr.write(`dossier written to ${String(outPath)}\n`);
}
