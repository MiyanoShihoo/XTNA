#!/usr/bin/env node
/**
 * XTNA dossier exporter: turn an Evidence bundle into a reviewable Markdown document.
 *
 * It reports only what the bundle states. Missing sections stay missing; nothing is
 * reconstructed from guesswork.
 */
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const args = process.argv.slice(2);
const flag = (name) => {
  const index = args.indexOf(`--${name}`);
  return index >= 0 ? args[index + 1] : undefined;
};

const evidencePath = flag("evidence");
if (evidencePath === undefined) {
  process.stderr.write(
    "usage: node scripts/dossier.mjs --evidence <bundle.json> [--overlay <binary>] [--out report.md] [--title text]\n",
  );
  process.exit(2);
}

const bundle = JSON.parse(await readFile(resolve(evidencePath), "utf8"));
const title = flag("title") ?? "XTNA technical dossier";
const overlayBinary = flag("overlay");
const outPath = flag("out");

const artifacts = Array.isArray(bundle.artifacts) ? bundle.artifacts : [];
const records = Array.isArray(bundle.records) ? bundle.records : [];
const providers = Array.isArray(bundle.providers) ? bundle.providers : [];
const unknowns = Array.isArray(bundle.unknowns) ? bundle.unknowns : [];
const environments = Array.isArray(bundle.environments)
  ? bundle.environments
  : [];

const lines = [];
lines.push(`# ${title}`, "");
lines.push(
  `Generated by XTNA on ${new Date().toISOString()} from \`${evidencePath}\`.`,
  "",
);
lines.push(
  "> This document projects a stored Evidence bundle. It does not add observations;",
);
lines.push(
  "> every claim below is traceable to an evidence record in that bundle.",
  "",
);

lines.push("## Targets", "");
if (artifacts.length === 0)
  lines.push("No artifacts are recorded in this bundle.", "");
else {
  lines.push("| Format | Architecture | SHA-256 |", "| --- | --- | --- |");
  for (const artifact of artifacts)
    lines.push(
      `| ${artifact.format ?? "unknown"} | ${artifact.architecture ?? "—"} | \`${artifact.digest?.sha256 ?? "—"}\` |`,
    );
  lines.push("");
}

lines.push("## Records", "");
if (records.length === 0)
  lines.push("No evidence records are stored in this bundle.", "");
else {
  lines.push(
    "| Operation | Provider | Authority | Confidence | Limitations | Evidence |",
    "| --- | --- | --- | --- | ---: | --- |",
  );
  for (const record of records) {
    const limitations = Array.isArray(record.limitations)
      ? record.limitations.length
      : 0;
    const id = String(record.evidence_id ?? "");
    lines.push(
      `| ${record.operation ?? "—"} | ${record.provider?.id ?? "—"} | ${record.authority ?? "—"} | ${record.confidence ?? "—"} | ${String(limitations)} | \`${id.slice(0, 19)}…\` |`,
    );
  }
  lines.push("");
}

const limitations = [];
for (const record of records)
  for (const limitation of record.limitations ?? [])
    limitations.push(`${record.operation ?? "record"}: ${limitation}`);
const uniqueLimitations = [...new Set(limitations)];
lines.push("## Limitations", "");
if (uniqueLimitations.length === 0)
  lines.push("The bundle records no limitations.", "");
else
  for (const limitation of uniqueLimitations.slice(0, 200))
    lines.push(`- ${limitation}`);
lines.push("");

lines.push("## Unknowns", "");
if (unknowns.length === 0)
  lines.push("The bundle records no explicit unknowns.", "");
else {
  lines.push(
    "| Domain | Severity | Status | Question |",
    "| --- | --- | --- | --- |",
  );
  for (const unknown of unknowns.slice(0, 100))
    lines.push(
      `| ${unknown.domain ?? "—"} | ${unknown.severity ?? "—"} | ${unknown.status ?? "—"} | ${String(unknown.question ?? "").replaceAll("|", "\\|")} |`,
    );
  lines.push("");
}

lines.push("## Providers", "");
if (providers.length === 0) lines.push("No provider identity is recorded.", "");
else
  for (const provider of providers)
    lines.push(
      `- ${provider.id ?? "unknown"} ${provider.version ? `v${provider.version}` : ""}`,
    );
lines.push("");

if (environments.length > 0) {
  lines.push("## Environments", "");
  for (const environment of environments)
    lines.push(`- ${JSON.stringify(environment)}`);
  lines.push("");
}

if (overlayBinary !== undefined) {
  const overlay = JSON.parse(
    await readFile(resolve(overlayBinary), "utf8").catch(
      () => '{"entries":[]}',
    ),
  );
  lines.push("## Symbol overlay", "");
  if (!Array.isArray(overlay.entries) || overlay.entries.length === 0)
    lines.push("No overlay entries for this binary.", "");
  else {
    lines.push(
      "| Address | Kind | Confidence | Name | Type |",
      "| --- | --- | --- | --- | --- |",
    );
    for (const entry of overlay.entries)
      lines.push(
        `| \`${entry.address_hex}\` | ${entry.kind} | ${entry.confidence} | \`${entry.name}\` | ${entry.type ?? "—"} |`,
      );
    lines.push("");
  }
}

lines.push("## Reproduction", "");
lines.push("```bash");
lines.push(`git clone https://github.com/MiyanoShihoo/XTNA.git`);
lines.push(`cd XTNA && npm ci --ignore-scripts && npm run compile`);
lines.push(
  `node scripts/rea.mjs inspect-artifact <target> --format json --detail summary --evidence_output evidence.json`,
);
lines.push("```", "");

const markdown = `${lines.join("\n")}\n`;
if (outPath === undefined) process.stdout.write(markdown);
else {
  await writeFile(resolve(outPath), markdown, "utf8");
  process.stderr.write(`dossier written to ${String(outPath)}\n`);
}
