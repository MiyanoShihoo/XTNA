#!/usr/bin/env node
/**
 * Generate a typed, dependency-free client from a recorded HTTP capture.
 *
 * Accepts a HAR document (or any object with an `entries`/`log.entries`
 * array). Writes `client.ts`, `client.py`, or both into the output directory.
 * Nothing is executed and no network access happens.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const args = process.argv.slice(2);
const flag = (name) => {
  const index = args.indexOf(`--${name}`);
  return index >= 0 ? args[index + 1] : undefined;
};

const input = flag("in");
const output = flag("out");
const language = flag("lang") ?? "both";
const clientName = flag("name") ?? "ApiClient";
const baseUrl = flag("base-url") ?? "http://localhost:8080";

if (input === undefined || output === undefined) {
  process.stderr.write(
    "usage: node scripts/sdk-gen.mjs --in <capture.har> --out <dir> [--lang ts|py|both] [--name ApiClient] [--base-url http://localhost:8080]\n",
  );
  process.exit(2);
}
if (!["ts", "py", "both"].includes(language)) {
  process.stderr.write("--lang must be ts, py or both\n");
  process.exit(2);
}

const { generateClientSdk } = await import(
  pathToFileURL(resolve("dist/application/sdk/ClientSdkGeneration.js")).href
);

const document = JSON.parse(
  (await readFile(resolve(input), "utf8")).replace(/^\uFEFF/u, ""),
);
const sdk = generateClientSdk(document, {
  clientName,
  baseUrl,
  header: `Generated by XTNA from ${input}. Review before use.`,
});

const directory = resolve(output);
await mkdir(directory, { recursive: true });
const written = [];
if (language !== "py") {
  const path = join(directory, "client.ts");
  await writeFile(path, sdk.typescript, "utf8");
  written.push(path);
  const testPath = join(directory, "client.test.ts");
  await writeFile(testPath, sdk.typescriptTest, "utf8");
  written.push(testPath);
}
if (language !== "ts") {
  const path = join(directory, "client.py");
  await writeFile(path, sdk.python, "utf8");
  written.push(path);
  const testPath = join(directory, "test_client.py");
  await writeFile(testPath, sdk.pythonTest, "utf8");
  written.push(testPath);
}

process.stdout.write(
  `${JSON.stringify(
    {
      input: resolve(input),
      operations: sdk.operations.length,
      methods: sdk.operations.map((operation) => operation.name),
      files: written,
    },
    null,
    2,
  )}\n`,
);
