#!/usr/bin/env node
/**
 * Generate a stateful mock server from a recorded HTTP capture.
 *
 * The output is one dependency-free Node module: list/read/create/update/delete
 * over the collections the capture seeded, plus verbatim replay for any other
 * recorded request. Run it with `node <out>`.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const args = process.argv.slice(2);
const flag = (name) => {
  const index = args.indexOf(`--${name}`);
  return index >= 0 ? args[index + 1] : undefined;
};

const input = flag("in");
const output = flag("out");
const port = flag("port");
const persist = flag("persist");

if (input === undefined || output === undefined) {
  process.stderr.write(
    "usage: node scripts/mock-server.mjs --in <capture.har> --out <server.mjs> [--port 8080] [--persist state.json]\n",
  );
  process.exit(2);
}

const { buildMockModel, renderMockServer } = await import(
  pathToFileURL(resolve("dist/application/mock/MockServerGeneration.js")).href
);

const document = JSON.parse(
  (await readFile(resolve(input), "utf8")).replace(/^\uFEFF/u, ""),
);
const model = buildMockModel(document);
const source = renderMockServer(model, {
  ...(port === undefined ? {} : { port: Number(port) }),
  ...(persist === undefined ? {} : { persist: resolve(persist) }),
  header: `Generated by XTNA from ${input}. State starts from the capture; POST/PUT/PATCH/DELETE mutate it.`,
});

const target = resolve(output);
await mkdir(dirname(target), { recursive: true });
await writeFile(target, source, "utf8");

process.stdout.write(
  `${JSON.stringify(
    {
      input: resolve(input),
      output: target,
      routes: model.routes.map((route) => `${route.method} ${route.template}`),
      collections: Object.keys(model.seed),
      records: Object.fromEntries(
        Object.entries(model.seed).map(([name, items]) => [name, items.length]),
      ),
    },
    null,
    2,
  )}\n`,
);
